// The point on the globe that faces us: over the Caribbean, a little north of the equator.
const CENTER_LONGITUDE = -75;
const CENTER_LATITUDE = 18;

const radians = (degrees: number) => (degrees * Math.PI) / 180;
const round = (value: number) => Math.round(value * 10) / 10;

/**
 * Where a place appears on a globe of the given radius and center, seen from space. Places round the
 * back are moved to the globe's edge, which is where their outline leaves the side we can see.
 */
function project([longitude, latitude]: [number, number], cx: number, cy: number, radius: number) {
  const lat = radians(latitude);
  const lat0 = radians(CENTER_LATITUDE);
  const dLon = radians(longitude - CENTER_LONGITUDE);
  let x = Math.cos(lat) * Math.sin(dLon);
  let y = Math.cos(lat0) * Math.sin(lat) - Math.sin(lat0) * Math.cos(lat) * Math.cos(dLon);
  const facing = Math.sin(lat0) * Math.sin(lat) + Math.cos(lat0) * Math.cos(lat) * Math.cos(dLon);
  if (facing < 0) {
    const length = Math.hypot(x, y) || 1;
    x /= length;
    y /= length;
  }
  return `${round(cx + x * radius)} ${round(cy - y * radius)}`;
}

const outline = (coastline: Coastline, cx: number, cy: number, radius: number) =>
  `M${coastline.map((point) => project(point, cx, cy, radius)).join(' L')} Z`;

