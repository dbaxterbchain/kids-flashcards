/** The land, ice and a few clouds, for a globe centered at (cx, cy). */
export function earthDetails(cx: number, cy: number, radius: number) {
  const land = LAND.map((coastline) => outline(coastline, cx, cy, radius)).join(' ');
  const ice = ICE.map((coastline) => outline(coastline, cx, cy, radius)).join(' ');
  const clouds = CLOUDS.map((cloud) => `M${cloud.map((point) => project(point, cx, cy, radius)).join(' L')}`).join(' ');
  // The sea ice around the North Pole.
  const arctic: Coastline = Array.from({ length: 36 }, (_, index) => [index * 10 - 180, 80]);
  return (
    `<path d="${outline(arctic, cx, cy, radius)}" fill="#e0f2fe" opacity="0.85"/>` +
    `<path d="${land}" fill="#22c55e" stroke="#15803d" stroke-width="1.5" stroke-linejoin="round"/>` +
    `<path d="${ice}" fill="#f8fafc" stroke="#cbd5e1" stroke-width="1.5" stroke-linejoin="round"/>` +
    `<filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="2"/></filter>` +
    `<path d="${clouds}" fill="none" stroke="#ffffff" stroke-width="7" stroke-linecap="round" stroke-linejoin="round" opacity="0.7" filter="url(#soft)"/>`
  );
}
